using System.Text;
using GemPrismUpscaler.Core.Configuration;

namespace GemPrismUpscaler.Core.Platform.Linux.Nested;

/// <summary>
/// Shell-sourceable state written by --nested-session and consumed by
/// gemprism-nested-run. Values are single-quoted; paths cannot contain a
/// newline and are validated by the caller.
/// </summary>
public sealed record NestedSessionState(
    int Pid,
    string WaylandDisplay,
    string Display,
    string SwaySocket,
    string Token,
    int Width,
    int Height)
{
    public static string DefaultPath
    {
        get
        {
            string dir = Path.GetDirectoryName(AppPaths.DefaultLogPath) ?? Path.GetTempPath();
            return Path.Combine(dir, "nested-session.env");
        }
    }

    public string ToEnvFile()
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Generated by GemPrismUpscaler --nested-session");
        builder.Append("GEMPRISM_NESTED_PID=").AppendLine(Pid.ToString());
        builder.Append("GEMPRISM_NESTED_WAYLAND=").AppendLine(Quote(WaylandDisplay));
        builder.Append("GEMPRISM_NESTED_DISPLAY=").AppendLine(Quote(Display));
        builder.Append("GEMPRISM_NESTED_SWAYSOCK=").AppendLine(Quote(SwaySocket));
        builder.Append("GEMPRISM_NESTED_TOKEN=").AppendLine(Quote(Token));
        builder.Append("GEMPRISM_NESTED_WIDTH=").AppendLine(Width.ToString());
        builder.Append("GEMPRISM_NESTED_HEIGHT=").AppendLine(Height.ToString());
        return builder.ToString();
    }

    public void Write(string? path = null)
    {
        path ??= DefaultPath;
        string? dir = Path.GetDirectoryName(path);
        if (!string.IsNullOrWhiteSpace(dir)) Directory.CreateDirectory(dir);
        File.WriteAllText(path, ToEnvFile());
        if (OperatingSystem.IsLinux())
            File.SetUnixFileMode(path, UnixFileMode.UserRead | UnixFileMode.UserWrite);
    }

    public static void Clear(string? path = null)
    {
        try
        {
            path ??= DefaultPath;
            if (File.Exists(path)) File.Delete(path);
        }
        catch { }
    }

    private static string Quote(string value)
        => "'" + value.Replace("'", "'\\''", StringComparison.Ordinal) + "'";
}
